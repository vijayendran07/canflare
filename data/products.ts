/**
 * Single source of truth for the catalogue.
 * - price: null  → the variant is hidden. A product with no priced variant is hidden.
 * - images: put the owner's photos in /public/products/ and list them as "/products/<file>".
 *   With no image the shop shows a neutral brand placeholder.
 * Prices can also be edited live from the admin (Products sheet) without touching this file.
 */
export type Variant = { label: string; price: number | null };

export type Product = {
  slug: string;
  category: string; // category slug, see categories below
  name: string;
  subtitle?: string;
  shortDescription: string;
  description: string;
  variants: Variant[];
  details: { label: string; value: string }[];
  images: string[];
  active: boolean;
  inStock: boolean;
  sortOrder: number;
  highlights: string[];
  /** Owner-chosen best seller – shown in the "Best sellers" row on the home page when at least one is set. */
  bestSeller?: boolean;
  /** Optional extra product info, shown on the product page only when filled in. */
  ingredients?: string;
  usage?: string;
  storage?: string;
  /** 360° spin: ordered photo frames of one product (12–36 images). The spinner only appears when this is filled. */
  spin?: string[];
  /** Combos made in the admin: slugs of the products inside */
  comboItems?: { slug: string; variant: string; qty: number }[];
  custom?: boolean;
};

